#!/usr/bin/env python3
"""Generate main/font_gen.h: antialiased 4bpp proportional faces from a TTF.

Run this only when the typefaces or sizes change; the generated header is
committed, so a normal `idf.py build` needs neither Python nor Pillow.

    python3 -m pip install pillow
    python3 tools/gen_font.py

The typeface is Inter (tools/fonts/Inter.ttf, SIL Open Font License 1.1 — see
tools/fonts/OFL.txt). It is a variable font, so the optical-size and weight axes
are set per face here rather than shipping three static files.
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
OUT = os.path.join(ROOT, 'main', 'font_gen.h')
TTF = os.path.join(ROOT, 'tools', 'fonts', 'Inter.ttf')

FIRST, LAST = 0x20, 0x7E
PAD = 8  # room for negative left bearings (j, italic-ish glyphs)

# name, pixel size, optical size, weight. Three sizes let the UI pick the
# largest one that fits a row: 22 px cap height 16, 18 px cap 13, 15 px cap 11.
FACES = (
    ('big', 22, 22, 600),
    ('mid', 18, 18, 600),
    ('small', 15, 14, 600),
)


def build_face(px, opsz, wght):
    """Rasterises 0x20-0x7E and returns (bits, glyphs, lineHeight, ascent)."""
    fnt = ImageFont.truetype(TTF, px)
    fnt.set_variation_by_axes([opsz, wght])
    ascent, descent = fnt.getmetrics()

    bits = bytearray()
    glyphs = []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        advance = int(round(fnt.getlength(ch)))

        img = Image.new('L', (advance + 2 * PAD, px * 3), 0)
        ImageDraw.Draw(img).text((PAD, ascent), ch, font=fnt, fill=255, anchor='ls')
        box = img.getbbox()
        if box is None:  # space and friends
            glyphs.append((len(bits), 0, 0, 0, 0, advance))
            continue

        x0, y0, x1, y1 = box
        w, h = x1 - x0, y1 - y0
        ink = img.crop(box).load()

        offset = len(bits)
        for row in range(h):
            for col in range(0, w, 2):
                hi = (ink[col, row] * 15 + 127) // 255
                lo = (ink[col + 1, row] * 15 + 127) // 255 if col + 1 < w else 0
                bits.append((hi << 4) | lo)

        glyphs.append((offset, w, h, x0 - PAD, y0 - ascent, advance))

    return bits, glyphs, ascent + descent, ascent


def emit_array(name, data, per_line=16):
    lines = ['static const uint8_t %s[%d] = {' % (name, len(data))]
    for i in range(0, len(data), per_line):
        lines.append('    ' + ' '.join('0x%02X,' % b for b in data[i:i + per_line]))
    lines.append('};')
    return lines


def main():
    out = [
        '/* Auto-generated by tools/gen_font.py from tools/fonts/Inter.ttf (OFL).',
        ' * 4bpp coverage, two pixels per byte, row-major; see Font.h for the layout.',
        ' * Do not edit: change FACES in the generator and re-run it. */',
        '#pragma once',
        '#include "Font.h"',
        '',
        'namespace font {',
        'namespace detail {',
        '',
    ]

    meta = []
    for name, px, opsz, wght in FACES:
        bits, glyphs, line_h, ascent = build_face(px, opsz, wght)
        out += emit_array('kBits_%s' % name, bits)
        out.append('')
        out.append('static const Glyph kGlyphs_%s[%d] = {' % (name, len(glyphs)))
        for (off, w, h, left, top, adv), code in zip(glyphs, range(FIRST, LAST + 1)):
            out.append('    {%d, %d, %d, %d, %d, %d}, /* %r */'
                       % (off, w, h, left, top, adv, chr(code)))
        out.append('};')
        out.append('')
        print('%-6s %2d px  %5d bytes  lineHeight %d  ascent %d'
              % (name, px, len(bits), line_h, ascent))
        meta.append((name, line_h, ascent))

    out.append('}  // namespace detail')
    out.append('')
    for name, line_h, ascent in meta:
        out.append('const Face %s = {"%s", detail::kBits_%s, detail::kGlyphs_%s, '
                   '0x%02X, 0x%02X, %d, %d};'
                   % (name, name, name, name, FIRST, LAST, line_h, ascent))
    out.append('')
    out.append('}  // namespace font')

    with open(OUT, 'w') as f:
        f.write('\n'.join(out) + '\n')
    print('wrote', OUT)


if __name__ == '__main__':
    sys.exit(main())
